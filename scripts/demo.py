if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="SOMA demo server")
    parser.add_argument(
        "--static", action="store_true",
        help="Export pre-recorded episode JSON instead of running live server"
    )
    parser.add_argument(
        "--out", type=str, default="results/demo_episode.json",
        help="Output path for --static export"
    )
    parser.add_argument(
        "--steps", type=int, default=200,
        help="Episode length for --static export"
    )
    args = parser.parse_args()

    if args.static:
        export_static(output_path=Path(args.out), n_steps=args.steps)
    else:
        asyncio.run(main_server())
