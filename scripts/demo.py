def export_static(
    output_path: Path = Path("results/demo_episode.json"),
    n_steps: int = 200,
):
    """
    Pre-record one episode as JSON for frontend static replay.
    Run this before the pitch and keep the file as a fallback.
    """
    print("Exporting static episode…")
    innate, ppo, detector, tolerance, learned = load_models()
    steps = list(run_episode_steps(innate, ppo, detector, tolerance, learned, n_steps=n_steps))

    from soma.envs.cyborg_wrapper import HOST_NAMES
    print("  Extracting learning curve from tb_logs…")
    learning_curve = _load_learning_curve()
    print(f"  Learning curve: {len(learning_curve)} points")

    episode = {
        "meta": {
            "n_steps":         len(steps),
            "host_names":      HOST_NAMES,
            "innate_threshold": float(innate.threshold_),
            "learning_curve":  learning_curve,
            "note":            "signaling game convergence panel is separate static image",
        },
        "steps": steps,
    }

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(episode, indent=2))

    n_atk = sum(s["host_states"][HOST_NAMES[0]]["compromised"] > 0 for s in steps)
    n_inn = sum(s["innate_fired"] for s in steps)
    print(f"  Steps: {len(steps)}  |  Innate fired: {n_inn}")
    print(f"  Saved → {output_path}")

    # Copy to frontend public folder if it exists
    dst = Path("frontend/public/demo_episode.json")
    if dst.parent.exists():
        import shutil
        shutil.copy(output_path, dst)
        print(f"  Copied → {dst}")


